"use client";

import { AlertTriangle, X } from "lucide-react";
import { useState } from "react";
import type { ScamDetectionResult } from "@/lib/utils/scam-detection";
import { getScamWarningMessage } from "@/lib/utils/scam-detection";

interface ScamWarningBannerProps {
  result: ScamDetectionResult;
  dismissible?: boolean;
}

export function ScamWarningBanner({
  result,
  dismissible = true,
}: ScamWarningBannerProps) {
  const [isDismissed, setIsDismissed] = useState(false);

  if (!result.is_suspicious || isDismissed) {
    return null;
  }

  const confidence = Math.round(result.confidence * 100);
  const message = getScamWarningMessage(result);

  // Determine severity color
  const getSeverityColor = () => {
    if (confidence >= 80) return "red";
    if (confidence >= 60) return "orange";
    return "yellow";
  };

  const severityColor = getSeverityColor();

  const colorClasses = {
    red: {
      border: "border-red-500/20",
      bg: "bg-red-500/10",
      text: "text-red-400",
      icon: "text-red-500",
    },
    orange: {
      border: "border-orange-500/20",
      bg: "bg-orange-500/10",
      text: "text-orange-400",
      icon: "text-orange-500",
    },
    yellow: {
      border: "border-yellow-500/20",
      bg: "bg-yellow-500/10",
      text: "text-yellow-400",
      icon: "text-yellow-500",
    },
  };

  const colors = colorClasses[severityColor];

  return (
    <div
      className={`relative rounded-lg border ${colors.border} ${colors.bg} p-4`}
    >
      <div className="flex gap-3">
        <AlertTriangle className={`h-5 w-5 flex-shrink-0 ${colors.icon}`} />
        <div className="flex-1">
          <p className={`mb-2 font-semibold ${colors.text}`}>{message}</p>
          {result.reasons.length > 0 && (
            <div className="space-y-1">
              <p className="text-sm font-medium">Detected issues:</p>
              <ul className="space-y-1 text-sm text-muted-foreground">
                {result.reasons.map((reason, index) => (
                  <li key={index} className="flex items-start gap-2">
                    <span className={colors.text}>•</span>
                    <span>{reason}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
          <p className="mt-3 text-xs text-muted-foreground">
            This warning is generated by our ScamShield AI system. Please
            exercise caution and verify all details before proceeding.
          </p>
        </div>
        {dismissible && (
          <button
            onClick={() => setIsDismissed(true)}
            className="flex-shrink-0 rounded-full p-1 hover:bg-white/10"
            aria-label="Dismiss warning"
          >
            <X className="h-4 w-4" />
          </button>
        )}
      </div>
    </div>
  );
}
